export function getLocalizedIkammArticles(lang = 'th') {
  const safeLang = lang === 'en' || lang === 'zh' ? lang : 'th'
  const contactLoc = IKAMM_CONTACT[safeLang]

  return IKAMM_ARTICLES.map((item) => {
    const loc = item[safeLang] || item.th
    const catLabel = CAT_LABELS[item.categoryId]?.[safeLang] || loc.pillar
    const itemSources = item.postUrl
      ? [{ label: 'Facebook Post (IKAMM HOME Thailand)', url: item.postUrl }, ...DEFAULT_SOURCES]
      : DEFAULT_SOURCES
    return {
      id: item.id,
      day: item.day,
      dayLabel: item.dayLabel || `Day ${item.day}`,
      isFbHighlight: Boolean(item.isFbHighlight),
      postUrl: item.postUrl || null,
      categoryId: item.categoryId,
      category: catLabel,
      pillar: loc.pillar,
      image: item.image,
      title: loc.title,
      readTime: loc.readTime,
      date: item.dateLabel?.[safeLang] || `Day ${item.day} / 30`,
      summary: loc.summary,
      tags: [...item.hashtags, catLabel, loc.pillar],
      hashtags: item.hashtags,
      cta: loc.cta,
      contact: {
        ...contactLoc,
        phones: IKAMM_CONTACT.phones,
        line: IKAMM_CONTACT.line,
        emails: IKAMM_CONTACT.emails,
        website: IKAMM_CONTACT.website,
        facebook: IKAMM_CONTACT.facebook,
        facebookName: IKAMM_CONTACT.facebookName,
      },
      sections: loc.sections,
      recommendations: loc.highlights,
      sources: itemSources,
    }
  })
}

